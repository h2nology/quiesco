// Turns ../scenario-details.md (the shootout report) into assets/benchmark-data.js.
// Usage: node site/build-data.mjs [path/to/scenario-details.md]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] ?? resolve(here, '../scenario-details.md'));
const md = readFileSync(src, 'utf8');

const NAMES = {
  S1: 'Log in and land on the list',
  S2: 'Validation message for an invalid email',
  S3: 'Debounced search',
  S4: 'Add an item that survives a refresh',
  S5: 'Delete an item through a confirm modal',
  S6: 'Scroll a long list to row 400',
  S7a: 'Chinese / Japanese input (text API)',
  S8: 'Native controls',
  S9: 'WebView',
  S10a: 'System permission (pre-granted)',
  S10b: 'System permission (tap the system dialog)',
  S11: 'An animation that never settles',
  S12: 'Swipe to delete',
  S13: 'Pull to refresh',
  S14: 'Long-press menu and drag to reorder',
  S15: 'Reanimated animation',
  S16: 'Polling and WebSocket',
  S17: 'Auto-dismissing toast',
  S18: 'Error state and retry',
  S19: 'Tabs and nested navigation',
  S20: 'Keyboard covering the input',
  S21: 'Deep link',
  S22: 'Local notification',
  S23: 'Background, foreground and persistence',
};
const TOOLS = ['Quiesco', 'Detox', 'Appium', 'Maestro'];
const num = (s) => (s === undefined || s.trim() === '' || /[–-]$/.test(s.trim()) && !/\d/.test(s) ? null : Number.parseFloat(s));
const cells = (line) => line.split('|').slice(1, -1).map((c) => c.trim().replace(/\*\*/g, ''));

// Suite table
const suite = {};
const suiteBlock = md.split('## 整套结果')[1].split('\n## ')[0];
for (const line of suiteBlock.split('\n')) {
  if (!/^\| (iOS|Android) \|/.test(line)) continue;
  const [plat, tool, median, p90, range, fails, rate, install, launch] = cells(line);
  const [min, max] = range.split('–').map(Number);
  const [f, runs] = fails.split('/').map((x) => Number(x.trim()));
  const ci = rate.match(/（(.+?)–(.+?)%）/);
  (suite[plat.toLowerCase()] ??= {})[tool.toLowerCase()] = {
    median: +median, p90: +p90, min, max, failures: f, runs,
    failRate: Number.parseFloat(rate), ci: [+ci[1], +ci[2]], install: +install, launch: +launch,
  };
}

// Per-scenario details
const scenarios = [];
const detail = md.split('## 各场景详情')[1];
for (const sec of detail.split('\n### ').slice(1)) {
  const id = sec.match(/^(S\d+[ab]?)/)[1];
  const sc = { id, name: NAMES[id], ios: {}, android: {}, errors: { ios: [], android: [] } };
  let plat = null;
  for (const line of sec.split('\n')) {
    if (line.startsWith('**iOS**')) plat = 'ios';
    else if (line.startsWith('**Android**')) plat = 'android';
    else if (plat && /^\| (Quiesco|Detox|Appium|Maestro) \|/.test(line)) {
      const [tool, median, p90, min, max, fails, rate, reset] = cells(line);
      const key = tool.toLowerCase();
      if (median === '跳过') { sc[plat][key] = { status: 'skipped' }; continue; }
      const [f, runs] = fails.split('/').map((x) => Number(x.trim()));
      const ci = rate.match(/（(.+?)–(.+?)%）/);
      sc[plat][key] = {
        status: median === '全部失败' ? 'failed' : 'ok',
        median: num(median), p90: num(p90), min: num(min), max: num(max),
        failures: f, runs, failRate: Number.parseFloat(rate), ci: [+ci[1], +ci[2]],
        reset: num(reset),
      };
    } else if (plat && /^- (Quiesco|Detox|Appium|Maestro) × \d+：/.test(line)) {
      const m = line.match(/^- (\w+) × (\d+)：`?(.*?)`?$/);
      sc.errors[plat].push({ tool: m[1].toLowerCase(), count: +m[2], message: m[3] });
    }
  }
  scenarios.push(sc);
}

const data = {
  session: 'm5-final-none',
  measured: '2026-11-24 → 2026-11-26 (JST)',
  runsPerCombo: 20,
  shared: { ios: ['S21', 'S22'], android: ['S10b', 'S22'] }, // excluded from the shared suite
  tools: TOOLS.map((t) => t.toLowerCase()),
  suite,
  scenarios,
};
const out = resolve(here, 'assets/benchmark-data.js');
writeFileSync(out, `// Generated by site/build-data.mjs from scenario-details.md. Do not edit by hand.\nwindow.BENCH = ${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${out}: ${scenarios.length} scenarios`);
for (const p of ['ios', 'android']) {
  const q = suite[p].quiesco.median;
  for (const t of ['appium', 'detox', 'maestro']) {
    const x = suite[p][t].median;
    console.log(p, t, `${((1 - q / x) * 100).toFixed(1)}% less time`, `${(x / q).toFixed(2)}x`);
  }
}
