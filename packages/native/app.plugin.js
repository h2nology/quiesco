// @ts-check
/**
 * Config plugin of @quiesco/native (Android part; iOS and the full @quiesco/expo-plugin come in Phase 4).
 * Add `"@quiesco/native"` to `plugins` in app.json. Decided by EXPO_PUBLIC_QUIESCO at prebuild time:
 *
 * - not an e2e build: exclude this module from autolinking, so the touch-injection code never reaches
 *   a production binary (docs/spikes/06-prod-strip.md). Being in devDependencies is not enough:
 *   autolinking would still find it.
 * - e2e build: allow cleartext traffic to localhost / 127.0.0.1 (the agent talks to ws://localhost
 *   through adb reverse; docs/spikes/05). Debug builds keep allowing all cleartext traffic (Metro over
 *   the LAN), because a networkSecurityConfig replaces `usesCleartextTraffic`.
 */
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod, withSettingsGradle } = require('@expo/config-plugins');

const PACKAGE = '@quiesco/native';
const MARK = '// @quiesco/native: excluded from autolinking (not an e2e build)';
const XML_NAME = 'quiesco_network_security_config';

/** @param {NodeJS.ProcessEnv} env */
function isE2E(env) {
  return env.EXPO_PUBLIC_QUIESCO === '1';
}

/** Insert the autolinking exclusion before `expoAutolinking.useExpoModules()`. Idempotent. */
function excludeFromSettingsGradle(src) {
  if (src.includes(MARK)) return src;
  if (!/^\s*expoAutolinking\.useExpoModules\(\)\s*$/m.test(src)) {
    throw new Error(`${PACKAGE}: settings.gradle has no expoAutolinking.useExpoModules(); cannot exclude the module`);
  }
  return src.replace(/^(\s*)expoAutolinking\.useExpoModules\(\)\s*$/m, `$1${MARK}\n$1expoAutolinking.exclude = ["${PACKAGE}"]\n$1expoAutolinking.useExpoModules()`);
}

/** @param {'localhost' | 'all'} kind */
function networkSecurityXml(kind) {
  const body =
    kind === 'all'
      ? '  <base-config cleartextTrafficPermitted="true" />\n'
      : '  <domain-config cleartextTrafficPermitted="true">\n    <domain includeSubdomains="false">localhost</domain>\n    <domain includeSubdomains="false">127.0.0.1</domain>\n  </domain-config>\n';
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by @quiesco/native for e2e builds. -->\n<network-security-config>\n${body}</network-security-config>\n`;
}

/** @param {import('@expo/config-plugins').ExpoConfig} config */
function withQuiescoNative(config, options = {}) {
  const env = /** @type {{ env?: NodeJS.ProcessEnv }} */ (options).env ?? process.env;
  if (!isE2E(env)) {
    return withSettingsGradle(config, (cfg) => {
      cfg.modResults.contents = excludeFromSettingsGradle(cfg.modResults.contents);
      return cfg;
    });
  }

  let ownConfig = true;
  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app === undefined) return cfg;
    const current = app.$['android:networkSecurityConfig'];
    if (current !== undefined && current !== `@xml/${XML_NAME}`) {
      ownConfig = false;
      console.warn(`${PACKAGE}: the app already sets android:networkSecurityConfig (${current}); make sure it allows cleartext to localhost`);
      return cfg;
    }
    app.$['android:networkSecurityConfig'] = `@xml/${XML_NAME}`;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      if (!ownConfig) return cfg;
      const appDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');
      for (const [sourceSet, kind] of /** @type {const} */ ([['main', 'localhost'], ['debug', 'all']])) {
        const dir = path.join(appDir, sourceSet, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, `${XML_NAME}.xml`), networkSecurityXml(kind));
      }
      return cfg;
    },
  ]);
}

module.exports = withQuiescoNative;
module.exports.excludeFromSettingsGradle = excludeFromSettingsGradle;
module.exports.networkSecurityXml = networkSecurityXml;
module.exports.isE2E = isE2E;
