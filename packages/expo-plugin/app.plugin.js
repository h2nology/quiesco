// @ts-check
/**
 * Expo config plugin of Quiesco (requirements.md §6.8). Add `"@quiesco/expo-plugin"` to `plugins` in
 * app.json / app.config.ts. Decided by EXPO_PUBLIC_QUIESCO at prebuild time:
 *
 * - not an e2e build: exclude @quiesco/native from autolinking on both platforms, so the touch
 *   injection code (private UIKit API on iOS) never reaches a production binary
 *   (docs/spikes/06-prod-strip.md). Being in devDependencies is not enough: autolinking would still
 *   find it.
 * - e2e build: keep the module and let the app reach the Quiesco host on localhost:
 *   - Android: cleartext traffic to localhost / 127.0.0.1 (ws:// through adb reverse, docs/spikes/05).
 *     Debug builds keep allowing all cleartext traffic (Metro over the LAN), because a
 *     networkSecurityConfig replaces `usesCleartextTraffic`.
 *   - iOS: `NSAllowsLocalNetworking` in App Transport Security (Expo sets it by default; this keeps it
 *     when an app config overrides NSAppTransportSecurity).
 */
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod, withInfoPlist, withPodfile, withSettingsGradle } = require('@expo/config-plugins');

const PLUGIN = '@quiesco/expo-plugin';
/** The package autolinking must leave out of production builds. */
const NATIVE_PACKAGE = '@quiesco/native';
const GRADLE_MARK = `// ${PLUGIN}: ${NATIVE_PACKAGE} excluded from autolinking (not an e2e build)`;
const PODFILE_MARK = `# ${PLUGIN}: ${NATIVE_PACKAGE} excluded from autolinking (not an e2e build)`;
const XML_NAME = 'quiesco_network_security_config';

/** @param {NodeJS.ProcessEnv | Record<string, string | undefined>} env */
function isE2E(env) {
  return env.EXPO_PUBLIC_QUIESCO === '1';
}

/** Android: set `expoAutolinking.exclude` before `expoAutolinking.useExpoModules()`. Idempotent. */
function excludeFromSettingsGradle(src) {
  if (src.includes(GRADLE_MARK)) return src;
  if (!/^\s*expoAutolinking\.useExpoModules\(\)\s*$/m.test(src)) {
    throw new Error(`${PLUGIN}: settings.gradle has no expoAutolinking.useExpoModules(); cannot exclude ${NATIVE_PACKAGE}`);
  }
  return src.replace(
    /^(\s*)expoAutolinking\.useExpoModules\(\)\s*$/m,
    `$1${GRADLE_MARK}\n$1expoAutolinking.exclude = ["${NATIVE_PACKAGE}"]\n$1expoAutolinking.useExpoModules()`,
  );
}

/**
 * iOS: pass `exclude:` to `use_expo_modules!` (forwarded to autolinking as --exclude). Idempotent.
 * Only the bare call generated by Expo is rewritten; a customized call fails loudly rather than being
 * guessed at.
 */
function excludeFromPodfile(src) {
  if (src.includes(PODFILE_MARK)) return src;
  const bare = /^(\s*)use_expo_modules!\s*$/m;
  if (!bare.test(src)) {
    throw new Error(
      `${PLUGIN}: the Podfile has no bare \`use_expo_modules!\` line; add \`exclude: ['${NATIVE_PACKAGE}']\` to it yourself for non-e2e builds`,
    );
  }
  return src.replace(bare, `$1${PODFILE_MARK}\n$1use_expo_modules!(exclude: ['${NATIVE_PACKAGE}'])`);
}

/** @param {'localhost' | 'all'} kind */
function networkSecurityXml(kind) {
  const body =
    kind === 'all'
      ? '  <base-config cleartextTrafficPermitted="true" />\n'
      : '  <domain-config cleartextTrafficPermitted="true">\n    <domain includeSubdomains="false">localhost</domain>\n    <domain includeSubdomains="false">127.0.0.1</domain>\n  </domain-config>\n';
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by ${PLUGIN} for e2e builds. -->\n<network-security-config>\n${body}</network-security-config>\n`;
}

/**
 * iOS e2e: make sure App Transport Security allows ws://localhost.
 * @param {Record<string, unknown>} plist
 */
function allowLocalNetworking(plist) {
  const ats = /** @type {Record<string, unknown>} */ (plist.NSAppTransportSecurity ?? {});
  return { ...plist, NSAppTransportSecurity: { ...ats, NSAllowsLocalNetworking: true } };
}

/** @param {import('@expo/config-plugins').ExportedConfig} config */
function withProductionExclusion(config) {
  config = withSettingsGradle(config, (cfg) => {
    cfg.modResults.contents = excludeFromSettingsGradle(cfg.modResults.contents);
    return cfg;
  });
  return withPodfile(config, (cfg) => {
    cfg.modResults.contents = excludeFromPodfile(cfg.modResults.contents);
    return cfg;
  });
}

/** @param {import('@expo/config-plugins').ExportedConfig} config */
function withE2EAndroid(config) {
  let ownConfig = true;
  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app === undefined) return cfg;
    const current = app.$['android:networkSecurityConfig'];
    if (current !== undefined && current !== `@xml/${XML_NAME}`) {
      ownConfig = false;
      console.warn(`${PLUGIN}: the app already sets android:networkSecurityConfig (${current}); make sure it allows cleartext to localhost`);
      return cfg;
    }
    app.$['android:networkSecurityConfig'] = `@xml/${XML_NAME}`;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      if (!ownConfig) return cfg;
      const appDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');
      for (const [sourceSet, kind] of /** @type {const} */ ([['main', 'localhost'], ['debug', 'all']])) {
        const dir = path.join(appDir, sourceSet, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, `${XML_NAME}.xml`), networkSecurityXml(kind));
      }
      return cfg;
    },
  ]);
}

/** @param {import('@expo/config-plugins').ExportedConfig} config */
function withE2EIos(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults = /** @type {typeof cfg.modResults} */ (allowLocalNetworking(cfg.modResults));
    return cfg;
  });
}

/**
 * @param {import('@expo/config-plugins').ExportedConfig} config
 * @param {{ env?: NodeJS.ProcessEnv | Record<string, string | undefined> }} [options] `env` is for tests.
 */
function withQuiesco(config, options = {}) {
  const env = options.env ?? process.env;
  if (!isE2E(env)) return withProductionExclusion(config);
  return withE2EIos(withE2EAndroid(config));
}

module.exports = withQuiesco;
module.exports.isE2E = isE2E;
module.exports.excludeFromSettingsGradle = excludeFromSettingsGradle;
module.exports.excludeFromPodfile = excludeFromPodfile;
module.exports.networkSecurityXml = networkSecurityXml;
module.exports.allowLocalNetworking = allowLocalNetworking;
